// Хадгалах утга (дэлгэцэнд шууд харагдана):
//   Улаанбаатар | Улаанбаатар, Баянзүрх дүүрэг | Дорнод аймаг | Архангай аймаг, Чулуут сум | Япон
function formatPlace(region, sub) {
  if (region === UB) return sub ? `${UB}, ${sub} дүүрэг` : UB;
  return sub ? `${region} аймаг, ${sub} сум` : `${region} аймаг`;
}

// Хадгалсан утгыг задлах: { where: 'mn'|'abroad'|null, region, sub, country }
function parsePlace(value) {
  const v = String(value || '').trim();
  if (!v) return { where: null };
  if (v === ABROAD) return { where: 'abroad', country: '' };
  if (COUNTRY_SET.has(v)) return { where: 'abroad', country: v };
  if (v === UB) return { where: 'mn', region: UB, sub: '' };
  let m = v.match(/^Улаанбаатар, (.+) дүүрэг$/);
  if (m && UB_DISTRICTS.includes(m[1])) return { where: 'mn', region: UB, sub: m[1] };
  if (REGION_MAP.has(v)) return { where: 'mn', region: v, sub: '' }; // хуучин "Дорнод"
  m = v.match(/^(.+) аймаг(?:, (.+) сум)?$/);
  if (m && REGION_MAP.has(m[1]) && m[1] !== UB) {
    const sub = m[2] || '';
    if (!sub || REGION_MAP.get(m[1])[1].includes(sub)) return { where: 'mn', region: m[1], sub };
  }
  return { where: null, raw: v };
}

// Статистикт бүлэглэх нэр: Монголд аймаг/нийслэлээр, гадаадад улсаар
function placeGroup(value) {
  const p = parsePlace(value);
  if (p.where === 'mn') return { key: p.region, label: p.region, abroad: false };
  if (p.where === 'abroad') return { key: 'abroad:' + (p.country || ''), label: p.country || 'Гадаад (улс тодорхойгүй)', abroad: true };
  const raw = String(value || '').trim();
  return raw ? { key: 'raw:' + raw, label: raw, abroad: false } : null;
}

// Маягтаас: place_where ('mn'|'abroad'), place_region, place_sub, place_country.
// Юу ч сонгоогүй бол одоогийн утгыг (байвал) хэвээр үлдээнэ.
function parsePlaceForm(body, current) {
  const where = body.place_where;
  if (where === 'mn') {
    const region = String(body.place_region || '');
    const r = REGION_MAP.get(region);
    if (!r) return { error: 'Аймаг эсвэл нийслэлээ сонгоно уу.' };
    const sub = String(body.place_sub || '');
    if (sub && !r[1].includes(sub)) return { error: 'Сум, дүүргээ жагсаалтаас сонгоно уу.' };
    return { city: formatPlace(region, sub) };
  }
  if (where === 'abroad') {
    const c = String(body.place_country || '');
    if (!COUNTRY_SET.has(c)) return { error: 'Амьдарч буй улсаа сонгоно уу.' };
    return { city: c };
  }
  return { city: current || null };
}

